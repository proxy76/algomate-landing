/**
 * Regenerates src/fonts.css from the installed @fontsource-variable packages.
 *
 *   node scripts/make-fonts-css.mjs
 *
 * Run it after bumping one of those packages; the output is committed.
 *
 * WHY THE FONTS ARE SELF-HOSTED
 *
 * They used to come from fonts.googleapis.com: a render-blocking stylesheet on
 * a third-party origin, then the font files from a second one — two extra
 * DNS + TLS handshakes before the first line of text could paint in its real
 * face, and every visitor's IP address handed to Google on every page view.
 * Served from /assets/ they ride the connection that is already open, are
 * cached for a year, and the site makes no third-party request at all — which
 * is what lets the Content-Security-Policy say `font-src 'self'`.
 *
 * WHY THIS FILE EXISTS INSTEAD OF IMPORTING THE PACKAGES' OWN CSS
 *
 * The rules below reproduce exactly what Google served for the old <link>, so
 * the switch changes where the bytes come from and nothing about how the page
 * looks. The packages' stylesheets differ from that in three ways that would
 * each have been a visible change:
 *
 *   · they name the families "Inter Variable" etc.; the site says "Inter"
 *   · they declare the full 100–900 weight range. Google declared only the
 *     weights the old URL asked for, and text set lighter or heavier than
 *     that clamps to the nearest declared weight. Opening the range would
 *     re-weight every such element.
 *   · Fraunces ships a `full` cut with the SOFT and WONK axes. index.css sets
 *     "SOFT" 50 on .font-display, but the file Google served never had that
 *     axis, so the setting has always been inert. The `opsz` cut used here
 *     (opsz + wght only) keeps it inert; `full` would soften every heading.
 *
 * Only the subsets a page actually uses are downloaded (unicode-range), so
 * listing Cyrillic and Greek costs nothing until a post contains them.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKG_DIR = path.join(ROOT, 'node_modules', '@fontsource-variable');
const OUT = path.join(ROOT, 'src', 'fonts.css');

/** family → the package stylesheet to mirror, and the weights Google declared. */
const FACES = [
  { family: 'Inter', pkg: 'inter', css: 'wght.css', weight: '400 700' },
  { family: 'Fraunces', pkg: 'fraunces', css: 'opsz.css', weight: '300 700' },
  // Italic was requested at 400 only. :root sets font-synthesis: none, so a
  // heavier italic renders at 400 — as it always has.
  { family: 'Fraunces', pkg: 'fraunces', css: 'opsz-italic.css', weight: '400' },
  { family: 'JetBrains Mono', pkg: 'jetbrains-mono', css: 'wght.css', weight: '300 600' },
];

const RULE = /\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g;

let out = `/* GENERATED by scripts/make-fonts-css.mjs — do not edit by hand.
   Self-hosted variable fonts, declared exactly as Google Fonts used to
   declare them. The reasoning is at the top of that script. */
`;

for (const face of FACES) {
  const file = path.join(PKG_DIR, face.pkg, face.css);
  const version = JSON.parse(
    fs.readFileSync(path.join(PKG_DIR, face.pkg, 'package.json'), 'utf-8')
  ).version;
  const css = fs.readFileSync(file, 'utf-8');
  let count = 0;

  out += `\n/* ${face.family} — @fontsource-variable/${face.pkg}@${version} (${face.css}) */\n`;

  for (const [, label, body] of css.matchAll(RULE)) {
    const style = /font-style:\s*(\w+)/.exec(body)[1];
    const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)[1];
    if (!fs.existsSync(path.join(PKG_DIR, face.pkg, 'files', woff2))) {
      throw new Error(`${woff2} is named in ${face.css} but is not in the package`);
    }
    out += `/* ${label} */
@font-face {
  font-family: "${face.family}";
  font-style: ${style};
  font-weight: ${face.weight};
  font-display: swap;
  src: url("../node_modules/@fontsource-variable/${face.pkg}/files/${woff2}") format("woff2");
  unicode-range: ${range.trim()};
}
`;
    count++;
  }

  if (count === 0) throw new Error(`no @font-face rules found in ${file}`);
}

fs.writeFileSync(OUT, out, 'utf-8');
console.log(`  ✓ wrote ${path.relative(ROOT, OUT)}`);
